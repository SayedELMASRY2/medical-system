import uuid
import enum
from datetime import datetime, timezone

from sqlalchemy import Column, String, DateTime, Enum, ForeignKey, Text, Boolean
from sqlalchemy.orm import relationship

from app.models.base import Base


class AlertSeverity(str, enum.Enum):
    LOW = "LOW"
    MONITOR = "MONITOR"
    CLINICAL_REVIEW = "CLINICAL_REVIEW"
    HIGH = "HIGH"


class CDSSAlert(Base):
    """
    Stores an alert or recommendation generated by the Clinical Decision Support System.
    """
    __tablename__ = "cdss_alerts"

    id = Column(String(36), primary_key=True, default=lambda: str(uuid.uuid4()))
    
    # Link to the patient profile
    patient_id = Column(
        String(36),
        ForeignKey("patient_profiles.id"),
        nullable=False,
        index=True,
    )

    severity = Column(Enum(AlertSeverity), nullable=False, default=AlertSeverity.MONITOR)
    message = Column(Text, nullable=False)
    resolved = Column(Boolean, default=False, nullable=False)

    created_at = Column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        nullable=False,
    )
    resolved_at = Column(DateTime(timezone=True), nullable=True)

    # Relationships
    patient = relationship(
        "PatientProfile",
        backref="cdss_alerts",
    )

    def __repr__(self):
        return f"<CDSSAlert(id={self.id}, severity='{self.severity}', resolved={self.resolved})>"
